List<String> filterCitySuggestions(String query) {
  final normalizedQuery = normalizeVietnameseText(query);
  if (normalizedQuery.isEmpty) {
    return kVietnamCitySuggestions;
  }

  return kVietnamCitySuggestions.where((city) {
    final normalizedCity = normalizeVietnameseText(city);
    return normalizedCity.contains(normalizedQuery);
  }).toList();
}
